/**
 * `npm run gen:frames`, the one way `test/support/frames.ts` is written.
 *
 * A golden is the frame the renderer drew, not a description of it: every screen in `test/support/screens.ts`, at the two
 * window sizes the spec names, rendered through the real `TerminalScreen` and the real renderer. This script is what makes
 * that true a second time, so a layout change shows up as a diff in the test file and a hand-edited golden is a thing
 * nobody has to do.
 *
 * It writes the file rather than printing it, because the test reads the module: `npm run gen:frames`, then read the diff.
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { disposeAll, NARROW, openScreen, WIDE } from "../test/support/screen.ts";
import { SHOTS } from "../test/support/screens.ts";

const out = fileURLToPath(new URL("../test/support/frames.ts", import.meta.url));

/** The name a shot's frame is exported under: `SECRET_100` for the secret screen at 100 columns. */
const name = (id: string, columns: number): string => `${id.toUpperCase()}_${columns}`;

const body: string[] = [];
for (const size of [WIDE, NARROW]) {
	for (const shot of SHOTS) {
		const harness = await openScreen(size);
		harness.screen.where({ title: shot.section, index: shot.index, total: shot.total });
		void shot.show(harness).catch(() => undefined);
		shot.type?.(harness);
		await harness.settle();
		await harness.settle();
		const rows = harness
			.frame()
			.split("\n")
			.map((row) => `\t${JSON.stringify(row)},`);
		body.push(`/** ${shot.section} at ${size.columns}x${size.rows}. */`);
		body.push(`export const ${name(shot.id, size.columns)} = [`, ...rows, '].join("\\n");', "");
		await harness.dispose();
	}
}
await disposeAll();

const header = `/**
 * The frames the wizard draws, golden: every screen at the two window sizes the spec names.
 *
 * Generated by \`npm run gen:frames\` from \`test/support/screens.ts\` through the real screen and the real renderer: the
 * frame is what the layout produced, not a description of it, so a change to either half shows up here as a diff. Trailing
 * blanks are trimmed so that a golden does not carry the width of the window it was taken in.
 */

`;
await writeFile(out, `${header}${body.join("\n")}`, "utf8");
console.log(`[gen:frames] wrote ${body.filter((line) => line.startsWith("export const")).length} frames to ${out}`);
